const asOf = "2026-10-18";

test("SSS: external schedule samples include MSC brackets, MPF and employer-only EC", () => {
  // Circular 2024-006, effective January 2025: 15% of rounded MSC, split 5/10.
  const cases = [
    { salary: 5_250, msc: 5_500, ee: 275, er: 550, ec: 10, mpf: 0, total: 835 },
    { salary: 14_750, msc: 15_000, ee: 750, er: 1_500, ec: 30, mpf: 0, total: 2_280 },
    { salary: 20_250, msc: 20_500, ee: 1_025, er: 2_050, ec: 30, mpf: 500, total: 3_105 },
    { salary: 34_750, msc: 35_000, ee: 1_750, er: 3_500, ec: 30, mpf: 15_000, total: 5_280 },
  ];
  for (const { salary, msc, ee, er, ec, mpf, total } of cases) {
    const actual = computeSss(salary, asOf);
    assert.equal(actual.monthlySalaryCredit, msc, String(salary));
    assert.equal(actual.employee, ee, String(salary));
    assert.equal(actual.employer, er, String(salary));
    assert.equal(actual.employerEC, ec, String(salary));
    assert.equal(actual.mpfMsc, mpf, String(salary));
    assert.equal(actual.total, total, String(salary));
  }
});

test("PhilHealth: 2026 official minimum / ordinary salary / maximum amounts", () => {
  // 5% premium, salary floor PHP10k, cap PHP100k, employed EE/ER halves.
  const cases = [
    { mbs: 8_000, base: 10_000, total: 500, employee: 250, employer: 250 },
    { mbs: 30_000, base: 30_000, total: 1_500, employee: 750, employer: 750 },
    { mbs: 100_000, base: 100_000, total: 5_000, employee: 2_500, employer: 2_500 },
    { mbs: 150_000, base: 100_000, total: 5_000, employee: 2_500, employer: 2_500 },
  ];
  for (const { mbs, ...expected } of cases) {
    assert.deepEqual(computePhilHealth(mbs, asOf), expected, String(mbs));
  }
  // Software reconciliation convention, NOT independently agency-certified:
  // when rounded premium contains an odd cent, assign that cent to employer.
  assert.deepEqual(computePhilHealth(10_000.20, asOf),
    { base: 10_000.20, total: 500.01, employee: 250, employer: 250.01 });
});

test("M-6: daily/hourly fixed MBS is distinct from variable gross earnings", () => {
  const daily = resolvePayProfile({
    payBasis: "daily", rateAmount: 1_000, standardWorkDaysPerMonth: 22, standardHoursPerDay: 8,
  });
  const hourly = resolvePayProfile({
    payBasis: "hourly", rateAmount: 125, standardWorkDaysPerMonth: 22, standardHoursPerDay: 8,
  });
  assert.equal(daily.monthlyEquivalent, 22_000);
  assert.equal(hourly.monthlyEquivalent, 22_000);
  assert.deepEqual(computePhilHealth(daily.monthlyEquivalent, asOf),
    { base: 22_000, total: 1_100, employee: 550, employer: 550 });
  assert.deepEqual(computePhilHealth(hourly.monthlyEquivalent, asOf),
    { base: 22_000, total: 1_100, employee: 550, employer: 550 });
  assert.equal(computePhilHealth(daily.monthlyEquivalent + 5_000, asOf).total, 1_350,
    "Incorrectly treating PHP5,000 illustrative OT/bonus as MBS changes the premium");
  // Actual employer workday divisor/basic-salary classification still needs review.
});

test("Pag-IBIG: current ordinary-member source illustration and boundary checks", () => {
  // Circular 460 (February 2024): ordinary-member MFS cap PHP10,000,
  // 1% EE at <=PHP1,500 and 2% EE/ER in the standard band.
  // Category, retro attribution and posted-correction decisions remain open.
  assert.deepEqual(computePagIbig(1_500, asOf),
    { fundSalary: 1_500, employeeRate: 0.01, employerRate: 0.02, employee: 15, employer: 30, total: 45 });
  assert.deepEqual(computePagIbig(10_000, asOf),
    { fundSalary: 10_000, employeeRate: 0.02, employerRate: 0.02, employee: 200, employer: 200, total: 400 });
  assert.equal(computePagIbig(30_000, asOf).total, 400);
});

test("BIR: independent tax table arithmetic at taxable pay (not gross basic)", () => {
  // RR 11-2018 Annex E, schedules effective January 2023 onward.
  const monthly: Array<[number, number]> = [[20_833, 0], [40_000, 3_208.40], [70_000, 9_375.05]];
  const semiMonthly: Array<[number, number]> = [[10_417, 0], [20_000, 1_604.10], [100_000, 21_770.80]];
  const annual: Array<[number, number]> = [[250_000, 0], [300_000, 7_500], [500_000, 42_500]];
  for (const [pay, tax] of monthly) assert.equal(computeMonthlyWithholdingTax(pay, false, asOf), tax);
  for (const [pay, tax] of semiMonthly) assert.equal(computeSemiMonthlyWithholdingTax(pay, false, asOf), tax);
  for (const [pay, tax] of annual) assert.equal(computeAnnualWithholdingTax(pay, false, asOf), tax);
});

test("13th-month: basic/12 and *internal* exact-cent half-up boundary", () => {
  // DOLE establishes basic compensation / 12; the half-cent handling is
  // a separate internal implementation choice, not an official sign-off.
  assert.equal(thirteenthMonthFromCentavos(120_000), 10_000);
  assert.equal(thirteenthMonthFromCentavos(120_000.05), 10_000);
  assert.equal(thirteenthMonthFromCentavos(120_000.06), 10_000.01);
  assert.equal(thirteenthMonthFromCentavos(120_000.18), 10_000.02);
  assert.throws(() => thirteenthMonthFromCentavos(Number.NaN), /INVALID/);
});

test("M-3: signed final-pay liability is read-only, never a negative payout", () => {
  const result = finalPaySignedBalance({
    grossFinalPay: "0.00", taxAdjustment: "-7500.00",
    finalStatutoryDeductions: "0.00", loanDeductions: "0.00",
  });
  assert.equal(result, -7_500);
  assert.equal(finalPaySignedBalance({
    grossFinalPay: "", taxAdjustment: "-7500.00",
    finalStatutoryDeductions: "0.00", loanDeductions: "0.00",
  }), null, "Missing financial evidence must not become an apparent zero");
});
