test("document download hash-verifies generated artifacts before serving", () => {
  const route = read("src/app/api/documents/[id]/route.ts");
  assert.ok(route.includes('document.sourceType === "generated"'));
  assert.ok(route.includes('createHash("sha256").update(body).digest("hex")'));
  assert.ok(route.includes("Generated document integrity verification failed."));
});

test("document listings expose provenance without exposing stored content", () => {
  const route = read("src/app/api/documents/route.ts");
  assert.ok(route.includes("sourceType: documents.sourceType"));
  assert.ok(route.includes("generationMetadata: documents.generationMetadata"));
  const getSection = route.slice(0, route.indexOf("export async function POST"));
  assert.equal(getSection.includes("content: documents.content"), false);
});

test("Automation Studio API exposes safe generated-document template metadata only", () => {
  const route = read("src/app/api/automation-studio/route.ts");
  const start = route.indexOf("documentTemplates: AUTOMATION_DOCUMENT_TEMPLATES.map");
  const end = route.indexOf("templates: AUTOMATION_WORKFLOW_TEMPLATES.map", start);
  const block = route.slice(start, end);
  assert.ok(block.includes("id: template.id"));
  assert.ok(block.includes("version: template.version"));
  assert.ok(block.includes("allowedTriggers"));
  assert.equal(block.includes("render: template.render"), false);
});

