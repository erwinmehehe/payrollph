test("document generation is employee scoped, idempotent, and immutable by source key", () => {
  const helper = read("src/lib/automation-document-generation.ts");
  assert.ok(helper.includes("eq(documents.sourceKey, sourceKey)"));
  assert.ok(helper.includes('sourceType: "generated"'));
  assert.ok(helper.includes("onConflictDoNothing().returning()"));
  assert.ok(helper.includes("document.sha256 !== sha256"));
  assert.ok(helper.includes("Generated-document idempotency conflict detected"));
  assert.ok(helper.includes("Employee document generated by governed automation"));
});

