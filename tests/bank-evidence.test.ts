test("bank file evidence hashes the exact generated bytes deterministically", () => {
  assert.equal(
    bankFileSha256("payroll\nrow\n"),
    bankFileSha256("payroll\nrow\n"),
  );
  assert.notEqual(
    bankFileSha256("payroll\nrow\n"),
    bankFileSha256("payroll\nrow 2\n"),
  );
});

test("accepted bank UAT requires a portal reference and rejected UAT requires a bank note", () => {
  assert.equal(parseBankPortalOutcome({ outcome: "accepted" }).ok, false);
  assert.equal(parseBankPortalOutcome({
    outcome: "accepted",
    portalReference: "BATCH-1234",
    submittedAt: "2026-10-03T08:00:00Z",
  }).ok, true);

  assert.equal(parseBankPortalOutcome({ outcome: "rejected" }).ok, false);
  assert.equal(parseBankPortalOutcome({
    outcome: "rejected",
    note: "Invalid bank upload column format",
  }).ok, true);
});

