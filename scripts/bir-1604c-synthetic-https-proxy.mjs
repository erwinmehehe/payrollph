import assert from "node:assert/strict";
import { createServer as createTlsServer } from "node:https";
import { request as httpRequest } from "node:http";
import { readFileSync } from "node:fs";

assert.equal(process.env.CI, "true");
assert.equal(process.env.BIR_SYNTHETIC_BROWSER_QA, "true");
assert.equal(new URL(process.env.DATABASE_URL ?? "").hostname, "127.0.0.1");

/**
 * Loopback TLS termination for production-equivalent __Host- Secure cookies.
 * Next.js start serves plain HTTP on 3000/3001. Browsers correctly reject
 * Secure session cookies over HTTP, so browser acceptance MUST use TLS.
 *
 * Keys and certificates are ephemeral runner-only, generated by openssl in CI.
 * No internet, remote addresses, credentials or production accounts involved.
 */
const creds = {
  key: readFileSync("/tmp/bir-synthetic-https.key"),
  cert: readFileSync("/tmp/bir-synthetic-https.crt"),
};

for (const [securePort, backendPort] of [[3443, 3000], [3444, 3001]]) {
  const server = createTlsServer(creds, (incoming, outgoing) => {
    const forward = httpRequest({
      hostname: "127.0.0.1",
      port: backendPort,
      method: incoming.method,
      path: incoming.url,
      headers: {
        ...incoming.headers,
        host: "127.0.0.1:" + securePort,
        "x-forwarded-host": "127.0.0.1:" + securePort,
        "x-forwarded-proto": "https",
      },
    }, response => {
      outgoing.writeHead(response.statusCode ?? 502, response.headers);
      response.pipe(outgoing);
    });
    forward.on("error", () => {
      if (!outgoing.headersSent) outgoing.writeHead(502);
      outgoing.end();
    });
    incoming.pipe(forward);
  });
  server.listen(securePort, "127.0.0.1");
  server.on("error", error => {
    console.error("BIR loopback TLS proxy could not start:", error instanceof Error ? error.name : "unknown");
    process.exitCode = 1;
  });
}
