// 1x1 PNG (fictional, generated bytes).
const PNG = Buffer.from("89504e470d0a1a0a0000000d4948445200000001000000010806000000" +
  "1f15c4890000000d49444154789c6300010000000500010d0a2db40000000049454e44ae426082", "hex");
const sha256 = (bytes) => createHash("sha256").update(bytes).digest("hex");

async function seedEmployer(label, nonce, makeSession) {
  const [org] = await db.insert(organizations).values({ name: "DL02 " + label + " " + nonce, legalName: "Fictional " + label }).returning();
  const [entity] = await db.insert(legalEntities).values({ organizationId: org.id, code: "DL02-" + label,
    legalName: "Fictional " + label + " Inc.", displayName: label, primaryEntity: true }).returning();
  const [owner] = await db.insert(users).values({ email: "dl02-owner-" + label + "-" + nonce + "@example.invalid",
    name: "DL02 owner " + label, passwordHash: "fictional-session-only", role: "owner", totpEnabled: true }).returning();
  await db.insert(userOrganizations).values({ userId: owner.id, organizationId: org.id, role: "owner", active: true });
  const ownerSession = await makeSession(owner.id);
  // Only fictional fixture sessions receive a verified MFA timestamp.
  await db.update(sessions).set({ mfaVerifiedAt: new Date() }).where(eq(sessions.id, ownerSession.id));
  const [worker, linkTarget] = await db.insert(employees).values(["W", "L"].map((suffix) => ({
    organizationId: org.id, legalEntityId: entity.id, employeeNo: "DL02-" + label + "-" + suffix + "-" + nonce,
    firstName: "DL02" + label + suffix, lastName: "Synthetic", title: "Fictional", avatarInitials: "DS",
    basicRate: "20000.00", startDate: "2026-01-05",
  }))).returning();
  const [ess] = await db.insert(users).values({ email: "dl02-ess-" + label + "-" + nonce + "@example.invalid",
    name: "DL02 employee " + label, passwordHash: "fictional-session-only", role: "employee", employeeId: worker.id }).returning();
  const [unlinked] = await db.insert(users).values({ email: "dl02-link-" + label + "-" + nonce + "@example.invalid",
    name: "DL02 unlinked " + label, passwordHash: "fictional-session-only", role: "employee" }).returning();
  await db.insert(userOrganizations).values([ess, unlinked].map((u) => ({ userId: u.id, organizationId: org.id, role: "employee", active: true })));
  const [run] = await db.insert(payrollRuns).values({ organizationId: org.id, legalEntityId: entity.id, periodLabel: "DL02 Sep A",
    periodStart: "2026-09-01", periodEnd: "2026-09-15", payDate: "2026-09-16", status: "Released" }).returning();
  await db.insert(payrollEntries).values({ payrollRunId: run.id, employeeId: worker.id, grossPay: "10000.00", deductions: "1000.00",
    netPay: "9000.00", lineItems: [{ code: "BASIC", amount: 10000 }] });
  const content = "Fictional DL02 policy for " + label + ": acknowledge receipt of the handbook.";
  const [policy] = await db.insert(hcmPolicyVersions).values({ organizationId: org.id, policyCode: "DL02-" + label, title: "DL02 handbook " + label,
    version: "1", status: "published", effectiveFrom: "2026-01-01", content, contentSha256: sha256(Buffer.from(content)),
    createdByUserId: owner.id, createdByName: owner.name }).returning();
  const [assignment] = await db.insert(hcmPolicyAssignments).values({ organizationId: org.id, policyId: policy.id, employeeId: worker.id }).returning();
  const [term] = await db.insert(hcmEmploymentTerms).values({ organizationId: org.id, employeeId: worker.id, employmentType: "Probationary",
    termKind: "probationary", effectiveFrom: "2026-01-05", status: "active", reason: "Fictional DL02 term", requestedBy: owner.name }).returning();
  const [decision] = await db.insert(hcmEmploymentTermDecisions).values({ organizationId: org.id, employeeId: worker.id,
    employmentTermId: term.id, decisionKind: "regularize", effectiveDate: "2026-07-05", reason: "Fictional DL02 decision",
    requestedByUserId: owner.id, requestedBy: owner.name }).returning();
  await db.insert(essEmployeePhotos).values({ employeeId: worker.id, organizationId: org.id, mimeType: "image/png",
    byteSize: PNG.length, sealedPhoto: encryptProfilePhoto(PNG), contentSha256: sha256(PNG) });
  return { org, entity, owner, ownerCookie: ownerSession.cookie, worker, linkTarget, ess, essCookie: (await makeSession(ess.id)).cookie,
    unlinked, unlinkedCookie: (await makeSession(unlinked.id)).cookie, policy, assignment, decision };
}

async function victimSnapshot(victim) {
  const org = victim.org.id;
  return {
    reports: await db.select().from(savedReportDefinitions).where(eq(savedReportDefinitions.organizationId, org)),
    policies: await db.select().from(hcmPolicyVersions).where(eq(hcmPolicyVersions.organizationId, org)),
    assignments: await db.select().from(hcmPolicyAssignments).where(eq(hcmPolicyAssignments.organizationId, org)),
    notes: await db.select().from(hcmEmploymentDecisionNotes).where(eq(hcmEmploymentDecisionNotes.organizationId, org)),
    photos: await db.select().from(essEmployeePhotos).where(eq(essEmployeePhotos.organizationId, org)),
    links: await db.select({ id: users.id, employeeId: users.employeeId }).from(users)
      .where(inArray(users.id, [victim.ess.id, victim.unlinked.id])),
    audit: await db.select().from(auditEvents).where(eq(auditEvents.organizationId, org)),
  };
}

export async function verifyDl02TenantIsolation(f, { request, expectStatus, makeSession }) {
  assert.equal(process.env.CI, "true");
  assert.equal(process.env.TENANT_SECOND_PASS_MODE, "isolated-ci-only");
  assert.equal(process.env.TENANT_DL02_PROOF, "isolated-ci-only");
  const nonce = randomUUID().replaceAll("-", "").slice(0, 10);
  const employers = []; await reserveHighSyntheticIds();
  for (const label of ["VICTIM", "ATTA", "ATTB"]) employers.push(await seedEmployer(label, nonce, makeSession));
  const victim = employers[0];
  const [victimReport] = await db.insert(savedReportDefinitions).values({ organizationId: victim.org.id, userId: victim.owner.id,
    name: "Victim-only saved report", reportKey: "headcount", selectedFields: ["department"] }).returning();
  for (const id of [victimReport.id, victim.policy.id, victim.assignment.id, victim.decision.id, victim.worker.id]) {
    assert.ok(Number.isSafeInteger(id) && id > 6, "Victim-only DL02 ID must really exist and exceed 6: " + id);
  }
  const victimBefore = await victimSnapshot(victim);
  const dates = { startDate: "2026-09-01", endDate: "2026-09-30" };

  for (const idx of [1, 2]) {
    const own = employers[idx];
    const org = own.org;
    const cookie = own.ownerCookie;

    // Saved report definitions: create, list, edit, delete own; victim employer and victim row denied.
    const ownSavedPost = expectStatus(await request("/api/report-builder/saved", { method: "POST", cookie,
      body: { organizationId: org.id, name: "Own DL02 report", reportKey: "headcount", selectedFields: ["department"], rowFilters: [] } }), 201, "Own saved report is created");
    const savedId = ownSavedPost.json?.report?.id;
    assert.equal(ownSavedPost.json?.report?.organizationId, org.id);
    expectStatus(await request("/api/report-builder/saved", { method: "POST", cookie,
      body: { organizationId: victim.org.id, name: "Forged victim report", reportKey: "headcount", selectedFields: [], rowFilters: [] } }), 403, "Victim employer saved report POST is denied");
    const ownSavedGet = expectStatus(await request("/api/report-builder/saved?organizationId=" + org.id, { cookie }), 200, "Own saved reports are listed");
    assert.ok(ownSavedGet.json.reports.some((row) => row.id === savedId) && ownSavedGet.json.reports.every((row) => row.id !== victimReport.id));
    expectStatus(await request("/api/report-builder/saved?organizationId=" + victim.org.id, { cookie }), 403, "Victim employer saved reports are not readable");
    const ownSavedPatch = expectStatus(await request("/api/report-builder/saved", { method: "PATCH", cookie,
      body: { organizationId: org.id, id: savedId, name: "Own DL02 report v2", reportKey: "headcount", selectedFields: ["status"], rowFilters: [] } }), 200, "Own saved report is edited");
    assert.equal(ownSavedPatch.json?.report?.name, "Own DL02 report v2");
    expectStatus(await request("/api/report-builder/saved", { method: "PATCH", cookie,
      body: { organizationId: victim.org.id, id: victimReport.id, name: "Forged", reportKey: "headcount", selectedFields: [], rowFilters: [] } }), 403, "Victim employer saved report PATCH is denied");
    expectStatus(await request("/api/report-builder/saved", { method: "PATCH", cookie,
      body: { organizationId: org.id, id: victimReport.id, name: "Forged", reportKey: "headcount", selectedFields: [], rowFilters: [] } }), 404, "Victim saved report ID does not resolve in own employer");
    const ownSavedDelete = expectStatus(await request("/api/report-builder/saved", { method: "DELETE", cookie,
      body: { organizationId: org.id, id: savedId } }), 200, "Own saved report is deleted");
    assert.equal(ownSavedDelete.json?.deleted, true);
    assert.equal((await db.select().from(savedReportDefinitions).where(eq(savedReportDefinitions.id, savedId))).length, 0);
    expectStatus(await request("/api/report-builder/saved", { method: "DELETE", cookie,
      body: { organizationId: victim.org.id, id: victimReport.id } }), 403, "Victim employer saved report DELETE is denied");
    expectStatus(await request("/api/report-builder/saved", { method: "DELETE", cookie,
      body: { organizationId: org.id, id: victimReport.id } }), 404, "Victim saved report ID cannot be deleted from own employer");

    // Workforce report builders (single verified legal employer).
    const ownHcmReportGet = expectStatus(await request("/api/hcm-report-builder?organizationId=" + org.id, { cookie }), 200, "Own HCM report catalog");
    assert.ok(Array.isArray(ownHcmReportGet.json?.fields) && ownHcmReportGet.json.fields.length > 0);
    expectStatus(await request("/api/hcm-report-builder?organizationId=" + victim.org.id, { cookie }), 403, "Victim HCM report catalog denied");
    const ownHcmReportPost = expectStatus(await request("/api/hcm-report-builder", { method: "POST", cookie,
      body: { organizationId: org.id, format: "json", dataset: "people", fields: ["headcount"], ...dates } }), 200, "Own HCM report runs");
    assert.deepEqual(ownHcmReportPost.json?.columns, ["headcount"]);
    expectStatus(await request("/api/hcm-report-builder", { method: "POST", cookie,
      body: { organizationId: victim.org.id, format: "json", dataset: "people", fields: ["headcount"], ...dates } }), 403, "Victim HCM report POST denied");
    const ownBuilderGet = expectStatus(await request("/api/reports/builder?organizationId=" + org.id, { cookie }), 200, "Own tenant report catalog");
    assert.ok(Array.isArray(ownBuilderGet.json?.fields?.people));
    expectStatus(await request("/api/reports/builder?organizationId=" + victim.org.id, { cookie }), 403, "Victim tenant report catalog denied");
    const ownBuilderPost = expectStatus(await request("/api/reports/builder", { method: "POST", cookie,
      body: { organizationId: org.id, format: "json", spec: { dataset: "people", fields: ["headcount"] }, ...dates } }), 200, "Own tenant report runs");
    assert.equal(ownBuilderPost.json?.source, "people");
    expectStatus(await request("/api/reports/builder", { method: "POST", cookie,
      body: { organizationId: victim.org.id, format: "json", spec: { dataset: "people", fields: ["headcount"] }, ...dates } }), 403, "Victim tenant report POST denied");

    // Performance evidence package export.
    const ownPerformanceEvidence = expectStatus(await request("/api/performance/evidence?organizationId=" + org.id + "&employeeId=" + own.worker.id, { cookie }), 200, "Own performance evidence exports");
    assert.match(ownPerformanceEvidence.headers.get("content-disposition") ?? "", new RegExp("performance-evidence-" + own.worker.id));
    expectStatus(await request("/api/performance/evidence?organizationId=" + victim.org.id + "&employeeId=" + victim.worker.id, { cookie }), 403, "Victim performance evidence denied");
    expectStatus(await request("/api/performance/evidence?organizationId=" + org.id + "&employeeId=" + victim.worker.id, { cookie }), 422, "Victim worker cannot be exported through own employer");

    // HCM document and policy controls.
    const ownHcmDocuments = expectStatus(await request("/api/hcm/documents?organizationId=" + org.id, { cookie }), 200, "Own HCM document controls");
    assert.ok(ownHcmDocuments.json.policies.some((row) => row.id === own.policy.id) && ownHcmDocuments.json.policies.every((row) => row.id !== victim.policy.id));
    expectStatus(await request("/api/hcm/documents?organizationId=" + victim.org.id, { cookie }), 403, "Victim HCM document controls denied");
    const ownPolicyDraft = expectStatus(await request("/api/hcm/documents", { method: "POST", cookie,
      body: { organizationId: org.id, action: "save-policy-draft", policyCode: "DL02-DRAFT", title: "Own draft", version: "1",
        effectiveFrom: "2026-10-01", content: "Fictional DL02 draft policy content for testing." } }), 201, "Own policy draft is created");
    assert.equal(ownPolicyDraft.json?.organizationId, org.id);
    expectStatus(await request("/api/hcm/documents", { method: "POST", cookie,
      body: { organizationId: victim.org.id, action: "save-policy-draft", policyCode: "FORGED", title: "Forged", version: "1",
        effectiveFrom: "2026-10-01", content: "Forged cross-employer policy content attempt." } }), 403, "Victim employer policy POST denied");
    expectStatus(await request("/api/hcm/documents", { method: "POST", cookie,
      body: { organizationId: org.id, action: "save-policy-draft", id: victim.policy.id, policyCode: "FORGED", title: "Forged", version: "1",
        effectiveFrom: "2026-10-01", content: "Forged cross-employer policy content attempt." } }), 404, "Victim policy ID does not resolve in own employer");

    // Employment-term decision evidence.
    const ownDecisionEvidence = expectStatus(await request("/api/hcm/employment-term-decisions/" + own.decision.id + "/evidence?organizationId=" + org.id, { cookie }), 200, "Own decision evidence packet");
    assert.ok(ownDecisionEvidence.json?.packet);
    expectStatus(await request("/api/hcm/employment-term-decisions/" + victim.decision.id + "/evidence?organizationId=" + victim.org.id, { cookie }), 403, "Victim decision evidence denied");
    expectStatus(await request("/api/hcm/employment-term-decisions/" + victim.decision.id + "/evidence?organizationId=" + org.id, { cookie }), 404, "Victim decision does not resolve in own employer");
    const ownDecisionNote = expectStatus(await request("/api/hcm/employment-term-decisions/" + own.decision.id + "/evidence", { method: "POST", cookie,
      body: { organizationId: org.id, noteKind: "hr_review", note: "Fictional HR review note." } }), 201, "Own decision note is added");
    assert.equal(ownDecisionNote.json?.note?.organizationId, org.id);
    expectStatus(await request("/api/hcm/employment-term-decisions/" + victim.decision.id + "/evidence", { method: "POST", cookie,
      body: { organizationId: victim.org.id, noteKind: "hr_review", note: "Forged cross-employer note." } }), 403, "Victim decision note POST denied");

    // Employee self-service: linked employee session, then the same session after membership revocation.
    const essCookie = own.essCookie;
    const ownPhotoGet = expectStatus(await request("/api/self/photo", { cookie: essCookie }), 200, "Own photo bytes");
    assert.equal(ownPhotoGet.headers.get("content-type"), "image/png");
    assert.ok(ownPhotoGet.text.includes("PNG") && ownPhotoGet.text.includes("IHDR"), "Own photo must be the real decrypted PNG bytes");
    const ownPhotoHead = expectStatus(await request("/api/self/photo", { method: "HEAD", cookie: essCookie }), 200, "Own photo exists");
    assert.equal(ownPhotoHead.headers.get("content-type"), "image/png");
    const ownContributionEvidence = expectStatus(await request("/api/self/contribution-evidence?agency=SSS&month=2026-09", { cookie: essCookie }), 200, "Own contribution evidence exports");
    assert.ok(ownContributionEvidence.text.includes(own.worker.employeeNo) && !ownContributionEvidence.text.includes(victim.worker.employeeNo));
    const ownPolicyAck = expectStatus(await request("/api/self/documents", { method: "POST", cookie: essCookie,
      body: { action: "acknowledge-policy", assignmentId: own.assignment.id } }), 200, "Own policy acknowledged");
    assert.equal(ownPolicyAck.json?.assignment?.status, "acknowledged");
    expectStatus(await request("/api/self/documents", { method: "POST", cookie: essCookie,
      body: { action: "acknowledge-policy", assignmentId: victim.assignment.id, organizationId: victim.org.id } }), 404, "Victim policy assignment cannot be acknowledged");
    const ownPhotoDelete = expectStatus(await request("/api/self/photo", { method: "DELETE", cookie: essCookie }), 200, "Own photo removed");
    assert.equal(ownPhotoDelete.json?.ok, true);
    expectStatus(await request("/api/self/photo", { cookie: essCookie }), 404, "Deleted own photo is gone");

    await db.update(userOrganizations).set({ active: false })
      .where(and(eq(userOrganizations.userId, own.ess.id), eq(userOrganizations.organizationId, org.id)));
    expectStatus(await request("/api/self/photo", { cookie: essCookie }), 403, "Former employee photo GET denied");
    expectStatus(await request("/api/self/photo", { method: "HEAD", cookie: essCookie }), 403, "Former employee photo HEAD denied");
    expectStatus(await request("/api/self/photo", { method: "DELETE", cookie: essCookie }), 403, "Former employee photo DELETE denied");
    expectStatus(await request("/api/self/contribution-evidence?agency=SSS&month=2026-09", { cookie: essCookie }), 403, "Former employee contribution evidence denied");
    expectStatus(await request("/api/self/documents", { method: "POST", cookie: essCookie,
      body: { action: "acknowledge-policy", assignmentId: own.assignment.id } }), 403, "Former employee policy POST denied");

    // Account linking: own employer number links; victim employee number is not found.
    expectStatus(await request("/api/self/payslips", { method: "POST", cookie: own.unlinkedCookie,
      body: { employeeNo: victim.linkTarget.employeeNo, organizationId: victim.org.id } }), 404, "Victim employee number cannot be claimed");
    const ownAccountLink = expectStatus(await request("/api/self/payslips", { method: "POST", cookie: own.unlinkedCookie,
      body: { employeeNo: own.linkTarget.employeeNo, organizationId: victim.org.id } }), 200, "Own employee number links (forged employer ignored)");
    assert.equal(ownAccountLink.json?.employeeId, own.linkTarget.id);
    const [linked] = await db.select({ employeeId: users.employeeId }).from(users).where(eq(users.id, own.unlinked.id));
    assert.equal(linked.employeeId, own.linkTarget.id);
  }

  const victimAfter = await victimSnapshot(victim);
  assert.deepEqual(victimAfter, victimBefore, "Denied DL02 requests leave victim reports, policies, notes, photos, links and audit unchanged");
}

// Reserve nontrivial *real* victim row IDs on a disposable localhost CI database.
// PostgreSQL sequences in previously unused tables otherwise produce id=1;
// never weaken the victim-ID assertions or forge non-existent identifiers.
async function reserveHighSyntheticIds() {
  assert.equal(new URL(process.env.DATABASE_URL).hostname, "127.0.0.1");
  assert.equal(new URL(process.env.SECURITY_SMOKE_URL).hostname, "127.0.0.1");
  await db.execute(sql`SELECT setval(pg_get_serial_sequence('saved_report_definitions', 'id')::regclass,
    GREATEST(6, COALESCE((SELECT MAX(id) FROM saved_report_definitions), 0),
      nextval(pg_get_serial_sequence('saved_report_definitions', 'id')::regclass)), true)`);
  await db.execute(sql`SELECT setval(pg_get_serial_sequence('hcm_policy_versions', 'id')::regclass,
    GREATEST(6, COALESCE((SELECT MAX(id) FROM hcm_policy_versions), 0),
      nextval(pg_get_serial_sequence('hcm_policy_versions', 'id')::regclass)), true)`);
  await db.execute(sql`SELECT setval(pg_get_serial_sequence('hcm_policy_assignments', 'id')::regclass,
    GREATEST(6, COALESCE((SELECT MAX(id) FROM hcm_policy_assignments), 0),
      nextval(pg_get_serial_sequence('hcm_policy_assignments', 'id')::regclass)), true)`);
  await db.execute(sql`SELECT setval(pg_get_serial_sequence('hcm_employment_term_decisions', 'id')::regclass,
    GREATEST(6, COALESCE((SELECT MAX(id) FROM hcm_employment_term_decisions), 0),
      nextval(pg_get_serial_sequence('hcm_employment_term_decisions', 'id')::regclass)), true)`);
  await db.execute(sql`SELECT setval(pg_get_serial_sequence('employees', 'id')::regclass,
    GREATEST(6, COALESCE((SELECT MAX(id) FROM employees), 0),
      nextval(pg_get_serial_sequence('employees', 'id')::regclass)), true)`);
}
