import assert from "node:assert/strict";

export const LOCAL_METADATA_OPTIONS =
  "-c neon.project_id=ci-fictional-project -c neon.branch_id=br-fictional-branch -c neon.endpoint_id=ep-fictional-endpoint";

/** Gate must execute before importing any DB modules, creating a session, or issuing HTTP. */
export function requireDisposableDbTarget(env = process.env) {
  const reject = why => { throw new Error("DB_TARGET_QA_REFUSED: " + why); };
  const required = [
    [env.CI === "true" && env.GITHUB_ACTIONS === "true", "GitHub CI only"],
    [env.TENANT_SECOND_PASS_MODE === "isolated-ci-only", "isolated tenant profile"],
    [env.TENANT_RUNTIME_DB_TARGET_MODE === "fictional-disposable-only", "explicit fictional opt-in"],
    [env.NODE_ENV === undefined, "runner must unset NODE_ENV"],
    [env.SECURITY_SMOKE_URL === "http://127.0.0.1:3000", "loopback HTTP only"],
    [env.DATABASE_URL === "postgresql://postgres:postgres@127.0.0.1:5432/app_db",
      "disposable local app_db only"],
    [env.PGOPTIONS === LOCAL_METADATA_OPTIONS, "fixed synthetic metadata only"],
    [env.DEMO_MODE === "false", "demo mode forbidden"],
    [env.WORKER_ENABLED === "false" && env.CENTRAL_SCHEDULER_ENABLED === "false",
      "background workers and scheduler disabled"],
    [env.PAYMONGO_DISBURSEMENTS_ENABLED === "false" &&
     env.XENDIT_PAYOUTS_ENABLED === "false" &&
     env.XENDIT_BILLING_ENABLED === "false", "financial providers disabled"],
    [/^[a-f0-9]{64}$/.test(env.READINESS_TOKEN ?? ""),
      "ephemeral 256-bit token expected"],
  ];
  for (const [ok, reason] of required) if (!ok) reject(reason);
  for (const key of [
    "NEON_DATABASE_URL", "DATABASE_URL_UNPOOLED", "PAYMONGO_SECRET_KEY",
    "XENDIT_SECRET_KEY", "XENDIT_API_KEY", "RESEND_API_KEY", "SMTP_URL",
  ]) if (env[key]) reject(key + " must be absent");
}

function assertHeaders(result) {
  // Next.js can append max-age=0 to the route's no-store response header.
  // Require no-store itself, and reject conflicting cache-enabling directives.
  const directives = (result.headers.get("cache-control") ?? "")
    .split(",").map(value => value.trim().toLowerCase()).filter(Boolean);
  assert.ok(directives.includes("no-store"), "private diagnostic must not cache");
  assert.ok(!directives.some(value =>
    value === "public" || value === "immutable" ||
    /^s-maxage\s*=/.test(value) ||
    (/^max-age\s*=/.test(value) && value !== "max-age=0")
  ), "private diagnostic must not advertise cacheable content");
  assert.equal(result.headers.get("vary")?.toLowerCase(), "x-readiness-token",
    "shared caches must vary on the private token");
}

export function assertPrivateDenial(result, forbidden = []) {
  assert.equal(result.status, 404, "missing or invalid readiness token must be a hidden 404");
  assert.deepEqual(result.json, { error: "Not found." }, "private refusal must be identical");
  assertHeaders(result);
  for (const marker of forbidden) {
    assert.ok(!result.text.includes(marker), "denied request disclosed fictional identity");
    for (const [name, value] of result.headers.entries()) {
      assert.ok(!(name + ":" + value).includes(marker), "denied response headers disclosed identity");
    }
  }
}

export function assertRuntimeEvidence(result, expected, forbidden = []) {
  assert.equal(result.status, 200, "authenticated runtime proof must be a real 200");
  assertHeaders(result);
  const value = result.json;
  assert.ok(value && typeof value === "object" && !Array.isArray(value), "real JSON proof required");
  assert.deepEqual(Object.keys(value).sort(), [
    "database", "deploymentEnvironment", "deploymentSha", "evidenceScope",
    "generatedAt", "schemaPresence",
  ].sort(), "no undocumented operational payload fields");
  assert.equal(value.deploymentSha, null, "CI must not impersonate a deployed revision");
  assert.equal(value.deploymentEnvironment, null, "CI must not impersonate Vercel deployment");
  assert.equal(value.evidenceScope,
    "PRIVATE_RUNTIME_SESSION_IDENTITY_ONLY_NOT_MIGRATION_APPROVAL");
  assert.ok(Number.isFinite(Date.parse(value.generatedAt)), "real timestamp required");
  assert.ok(Math.abs(Date.now() - Date.parse(value.generatedAt)) < 60000,
    "proof must be generated by current localhost server");
  assert.deepEqual(value.database, expected.database, "actual DB session identity required");
  assert.deepEqual(value.schemaPresence, expected.schemaPresence,
    "source catalog-table counts required, not invented proof");
  for (const marker of forbidden) {
    assert.ok(!result.text.includes(marker), "authenticated proof disclosed a fictional identity or secret");
  }
  for (const forbiddenKey of ["connectionString", "password", "employeeId", "organizationId",
    "email", "employees", "payrollRuns", "auditEvents", "tenantData"]) {
    assert.ok(!Object.hasOwn(value, forbiddenKey), "private operational response leaked tenant keys");
  }
}

export function assertImmutableSnapshots(before, after) {
  assert.deepEqual(after, before, "diagnostic HTTP requests mutated tenant or payroll data");
}
