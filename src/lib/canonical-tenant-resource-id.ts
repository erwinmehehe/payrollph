/** Never coerce or alias a path/query resource to a different employer-owned ID. */
export function canonicalTenantResourceId(value: unknown): number | null {
  if (typeof value !== "string" || !/^[1-9][0-9]*$/.test(value)) return null;
  const id = Number(value);
  return Number.isSafeInteger(id) ? id : null;
}
