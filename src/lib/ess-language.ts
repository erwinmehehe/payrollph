/** Unknown text (especially source/payroll evidence) stays byte-for-byte as supplied. */
export function essText(language: EssLanguage, english: string): string {
  if (language !== "fil") return english;
  return Object.prototype.hasOwnProperty.call(taglishCopy, english)
    ? taglishCopy[english]
    : english;
}

export function parseEssLanguage(input: unknown): EssLanguage {
  return input === "fil" ? "fil" : "en";
}
